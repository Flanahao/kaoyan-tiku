#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const dataPath = process.argv[2] || 'data/lilin880/lilin_880_shu1_full.json';
const catalogPath = process.argv[3] || 'data/lilin880/lilin_880_shu1_catalog.json';
const outputPath = process.argv[4] || 'js/lilin880-latex-data.js';

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function jsJson(value) {
  return JSON.stringify(value)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

const questions = readJson(dataPath);
const catalog = readJson(catalogPath);
if (!Array.isArray(questions)) throw new Error('full.json 顶层必须是数组');
if (!catalog || !Array.isArray(catalog.chapters)) throw new Error('catalog.json 缺少 chapters 数组');

const disciplineToSubject = {
  '高等数学': '高数',
  '线性代数': '线代',
  '概率论与数理统计': '概率论',
};

const recordsById = Object.fromEntries(questions.map((question) => [String(question.id), question]));
const chapters = catalog.chapters.map((catalogChapter) => {
  const chapterQuestions = questions
    .filter((question) => question.chapter_number === catalogChapter.chapter_number)
    .sort((a, b) => a.id - b.id);
  if (chapterQuestions.length !== catalogChapter.total) {
    throw new Error(
      `第 ${catalogChapter.chapter_number} 章题数不一致：full=${chapterQuestions.length}, catalog=${catalogChapter.total}`
    );
  }
  const discipline = catalogChapter.discipline;
  const subject = disciplineToSubject[discipline];
  if (!subject) throw new Error(`未知学科：${discipline}`);
  const chapterNumber = catalogChapter.chapter_number;
  return {
    id: `latex880-ch${String(chapterNumber).padStart(2, '0')}`,
    number: 300 + chapterNumber,
    name: `李林880·LaTeX - ${catalogChapter.chapter_name}`,
    short: catalogChapter.chapter_name,
    total: chapterQuestions.length,
    cols: 5,
    wb: '李林880·LaTeX',
    subj: subject,
    contentType: 'latex',
    contentKey: `lilin880_shu1_ch${String(chapterNumber).padStart(2, '0')}`,
    questionIds: chapterQuestions.map((question) => question.id),
    // 不使用末尾括号，避免被现有 ensureGroups() 误判为子题。
    labels: chapterQuestions.map(
      (question) => `${question.level}·${question.type} ${question.question_number}`
    ),
  };
});

const output = `// Generated by scripts/build-lilin880-latex.mjs. Do not edit manually.\n` +
  `window.LILIN880_LATEX_DATA = ${jsJson({ recordsById })};\n` +
  `window.LILIN880_LATEX_CHAPTERS = ${jsJson(chapters)};\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output, 'utf8');
console.log(`generated ${outputPath}: ${questions.length} questions, ${chapters.length} chapters`);
